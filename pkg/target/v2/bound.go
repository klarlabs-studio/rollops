package targetv2

import (
	"context"
	"fmt"
)

// Bound is a Target together with the capabilities the host resolved for it —
// the manifest ceiling narrowed by the target's own runtime claim (see
// Capabilities.Narrow). Callers hold this rather than a bare Target, because
// it is the only thing that can answer what the target may do here: the
// target's claim alone ignores what the operator authorized, and a type
// assertion answers nothing at all when the target is a subprocess.
//
// The optional capabilities are reachable only through its methods, so the
// capability check cannot be skipped by calling the method directly.
type Bound struct {
	target Target
	caps   Capabilities
}

// NewBound ties a target to its resolved capabilities.
func NewBound(t Target, caps Capabilities) *Bound {
	return &Bound{target: t, caps: caps}
}

// Unwrap returns the underlying target. It exists for adapters that must pass
// the target on; using it to reach an optional capability defeats the point of
// this type.
func (b *Bound) Unwrap() Target { return b.target }

// Metadata identifies the target.
func (b *Bound) Metadata() Metadata { return b.target.Metadata() }

// Capabilities returns the resolved set, never the target's raw claim. A
// caller that could see the unnarrowed claim would be able to act on a
// capability the operator refused.
func (b *Bound) Capabilities(context.Context) (Capabilities, error) {
	return b.caps, nil
}

// Can reports whether the target may do this here.
func (b *Bound) Can(c Capability) bool { return b.caps.Has(c) }

// Inspect reports the live inventory.
func (b *Bound) Inspect(ctx context.Context, req InspectRequest) (ObservedState, error) {
	return b.target.Inspect(ctx, req)
}

// Plan reports what Apply would do, without doing it.
func (b *Bound) Plan(ctx context.Context, req PlanRequest) (PlanResult, error) {
	return b.target.Plan(ctx, req)
}

// Apply converges the target on the desired state. The idempotency key is
// checked here rather than in each target: a target that forgets the check is
// a target whose retries apply twice, and this is the one side that can be
// made to check once (§9.4).
func (b *Bound) Apply(ctx context.Context, req ApplyRequest) (ApplyResult, error) {
	if req.IdempotencyKey == "" {
		return ApplyResult{}, Failf(KindInvalid, "Apply", nil, "an idempotency key is required")
	}
	return b.target.Apply(ctx, req)
}

// Observe reports how an apply is going.
func (b *Bound) Observe(ctx context.Context, req ObserveRequest) (Observation, error) {
	return b.target.Observe(ctx, req)
}

// Rollback undoes an apply natively.
func (b *Bound) Rollback(ctx context.Context, req RollbackRequest) (RollbackResult, error) {
	if !b.Can(CapabilityNativeRollback) {
		return RollbackResult{}, Unsupported("Rollback", CapabilityNativeRollback)
	}
	return b.target.Rollback(ctx, req)
}

// Promote advances a partially rolled-out apply.
func (b *Bound) Promote(ctx context.Context, req PromoteRequest) (PromoteResult, error) {
	impl, err := capable[Promoter](b, CapabilityProgressiveDelivery, "Promote")
	if err != nil {
		return PromoteResult{}, err
	}
	return impl.Promote(ctx, req)
}

// DetectDrift compares live state against desired.
func (b *Bound) DetectDrift(ctx context.Context, req DriftRequest) (DriftResult, error) {
	impl, err := capable[Drifter](b, CapabilityDriftDetection, "DetectDrift")
	if err != nil {
		return DriftResult{}, err
	}
	return impl.DetectDrift(ctx, req)
}

// Prune removes the resources the target owns.
func (b *Bound) Prune(ctx context.Context, req PruneRequest) (PruneResult, error) {
	impl, err := capable[Pruner](b, CapabilityPrune, "Prune")
	if err != nil {
		return PruneResult{}, err
	}
	return impl.Prune(ctx, req)
}

// capable resolves an optional subinterface after the capability check has
// already passed. This is the one place a type assertion on a target is
// correct, and it is correct because a failure here is a contract violation
// rather than a branch: a target that declared the capability and does not
// implement it is broken, and saying "unsupported" instead would let it keep
// lying while the caller quietly fell back.
func capable[T any](b *Bound, c Capability, op string) (T, error) {
	var zero T
	if !b.Can(c) {
		return zero, Unsupported(op, c)
	}
	impl, ok := b.target.(T)
	if !ok {
		return zero, Failf(KindInternal, op, nil,
			"target %s declares %s but does not implement it",
			b.target.Metadata().Name, c)
	}
	return impl, nil
}

// IdempotencyKeyFor mints the key for one planned operation (§9.4). It is
// derived from durable identifiers rather than generated at call time, because
// the case the key exists for is a crash between the call and its response:
// a key minted per call is regenerated by the retry and defeats itself, where
// a key derived from stored state is the same key the lost call used.
//
// Two deployments that happen to plan an identical change get different keys.
// They are two intents, and replaying one as the other would be wrong.
func IdempotencyKeyFor(deploymentID, operationID string) string {
	return fmt.Sprintf("%s/%s", deploymentID, operationID)
}
